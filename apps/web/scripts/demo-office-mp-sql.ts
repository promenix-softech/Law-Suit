/**
 * Prints SQL that creates a second, fully separate synthetic demo office in Madhya Pradesh
 * (for showing multi-office isolation and a non-Maharashtra jurisdiction). Amounts, forum and
 * 12A are computed here with the domain functions; the SQL only stores them. Idempotent.
 *
 *   pnpm --filter web exec tsx scripts/demo-office-mp-sql.ts '<bcrypt hash of the demo password>' > mp.sql
 *
 * Only the bcrypt hash goes into the SQL, never the password. Synthetic data only.
 */
import { calculateInterest, commercialCheck, recoveryForum, rupees } from "@civil-suits/domain";

const hash = process.argv[2];
if (!hash || !/^\$2[aby]\$\d{2}\$[./A-Za-z0-9]{53}$/.test(hash)) {
  console.error("Pass the bcrypt hash of the demo password as the first argument.");
  process.exit(1);
}

const ORG = "Demo Law Chambers, Bhopal (Synthetic)";
const DOMAIN = "demo-mp.civilsuits.test";
const USERS = [
  { key: "admin", name: "Arun Demo Admin", role: "admin" },
  { key: "drafter", name: "Divya Demo Drafter", role: "drafter" },
  { key: "approver", name: "Alok Demo Approver", role: "approver" },
  { key: "field", name: "Faisal Demo Field", role: "field" },
] as const;
const CASES = [
  { borrower: "Rajesh Demo Sharma", principal: 1_60_000, status: "docs_uploaded", bank: "SBI" },
  { borrower: "Sunita Test Verma", principal: 2_40_000, status: "notice_sent", bank: "PNB" },
  { borrower: "Amit Sample Tiwari", principal: 4_10_000, status: "mediation_12a", bank: "SBI" },
  { borrower: "Pooja Fake Yadav", principal: 7_80_000, status: "drafting", bank: "PNB" },
  { borrower: "Vikas Demo Chouhan", principal: 11_20_000, status: "in_approval", bank: "SBI" },
  { borrower: "Neha Test Mishra", principal: 18_50_000, status: "drafting", bank: "SBI" },
] as const;

const q = (s: string) => `'${s.replaceAll("'", "''")}'`;

const caseRows = CASES.map((c, i) => {
  const principal = rupees(c.principal);
  const interest = calculateInterest({
    principalPaise: principal, rateBps: 1100, from: "2025-05-31", to: "2026-10-20", compounding: "quarterly",
  });
  const check = commercialCheck({ specifiedValuePaise: interest.totalPaise, lenderIsBank: true });
  const forum = recoveryForum({ claimPaise: interest.totalPaise, lenderIsBank: true }).forum;
  return {
    ...c,
    no: `MP-DEMO-2026-${String(i + 1).padStart(4, "0")}`,
    court: forum === "drt" ? "drt" : check.isCommercial ? "commercial" : "civil",
    suitType: check.isCommercial ? "commercial" : "summary_o37",
    principal,
    total: interest.totalPaise,
    isCommercial: check.isCommercial,
    needs12A: check.needs12A,
    i,
  };
});

console.log(`-- Generated by apps/web/scripts/demo-office-mp-sql.ts. Synthetic data only.
do $demo$
declare
  org uuid;
  uid uuid;
  ids jsonb := '{}';
  sbi uuid; pnb uuid; sbi_br uuid; pnb_br uuid;
  courts jsonb := '{}';
  cid uuid;
begin
  select id into org from public.organizations where name = ${q(ORG)};
  if org is null then
    insert into public.organizations (name) values (${q(ORG)}) returning id into org;
  end if;
`);

for (const u of USERS) {
  const email = `${u.key}@${DOMAIN}`;
  console.log(`  select id into uid from auth.users where email = ${q(email)};
  if uid is null then
    uid := gen_random_uuid();
    insert into auth.users (instance_id, id, aud, role, email, encrypted_password, email_confirmed_at,
      raw_app_meta_data, raw_user_meta_data, created_at, updated_at,
      confirmation_token, recovery_token, email_change_token_new, email_change,
      email_change_token_current, phone_change, phone_change_token, reauthentication_token)
    values ('00000000-0000-0000-0000-000000000000', uid, 'authenticated', 'authenticated', ${q(email)}, ${q(hash)}, now(),
      '{"provider":"email","providers":["email"]}', '{}', now(), now(), '', '', '', '', '', '', '', '');
    insert into auth.identities (id, user_id, provider_id, provider, identity_data, created_at, updated_at, last_sign_in_at)
    values (gen_random_uuid(), uid, uid::text, 'email',
      jsonb_build_object('sub', uid::text, 'email', ${q(email)}, 'email_verified', true), now(), now(), now());
  end if;
  if exists (select 1 from public.profiles where id = uid and org_id <> org) then
    raise exception '% belongs to another office', ${q(email)};
  end if;
  if not exists (select 1 from public.profiles where id = uid) then
    insert into public.profiles (id, org_id, full_name) values (uid, org, ${q(u.name)});
  end if;
  insert into public.user_roles (user_id, org_id, role) values (uid, org, ${q(u.role)}) on conflict do nothing;
  ids := ids || jsonb_build_object(${q(u.key)}, uid);
`);
}

console.log(`
  insert into public.banks (org_id, name, short_code) values (org, 'State Bank of India', 'SBI')
    on conflict (org_id, short_code) do nothing;
  insert into public.banks (org_id, name, short_code) values (org, 'Punjab National Bank', 'PNB')
    on conflict (org_id, short_code) do nothing;
  select id into sbi from public.banks where org_id = org and short_code = 'SBI';
  select id into pnb from public.banks where org_id = org and short_code = 'PNB';
  select id into sbi_br from public.bank_branches where org_id = org and ifsc = 'SBIN0DEMO11';
  if sbi_br is null then
    insert into public.bank_branches (org_id, bank_id, branch_name, ifsc)
      values (org, sbi, 'Demo Branch, Bhopal', 'SBIN0DEMO11') returning id into sbi_br;
  end if;
  select id into pnb_br from public.bank_branches where org_id = org and ifsc = 'PUNB0DEMO12';
  if pnb_br is null then
    insert into public.bank_branches (org_id, bank_id, branch_name, ifsc)
      values (org, pnb, 'Demo Branch, Indore', 'PUNB0DEMO12') returning id into pnb_br;
  end if;
`);

const COURTS = [
  { key: "civil", name: "Civil Judge, Bhopal (Demo)", district: "Bhopal", type: "civil" },
  { key: "commercial", name: "Commercial Court, Bhopal (Demo)", district: "Bhopal", type: "commercial" },
  { key: "drt", name: "Debts Recovery Tribunal, Jabalpur (Demo)", district: "Jabalpur", type: "drt" },
];
for (const c of COURTS) {
  console.log(`  select id into cid from public.courts where org_id = org and name = ${q(c.name)};
  if cid is null then
    insert into public.courts (org_id, name, district, court_type, state)
      values (org, ${q(c.name)}, ${q(c.district)}, ${q(c.type)}, 'MP') returning id into cid;
  end if;
  courts := courts || jsonb_build_object(${q(c.key)}, cid);
`);
}

for (const c of caseRows) {
  console.log(`  if not exists (select 1 from public.cases where org_id = org and case_no_internal = ${q(c.no)}) then
    insert into public.cases (org_id, bank_branch_id, court_id, case_no_internal, status, suit_type, claim_amount_paise,
      specified_value_paise, is_commercial, needs_12a, assigned_drafter, assigned_approver, created_by)
    values (org, ${c.bank === "SBI" ? "sbi_br" : "pnb_br"}, (courts ->> ${q(c.court)})::uuid, ${q(c.no)}, ${q(c.status)},
      ${q(c.suitType)}, ${c.total}, ${c.total}, ${c.isCommercial}, ${c.needs12A},
      (ids ->> 'drafter')::uuid, (ids ->> 'approver')::uuid, (ids ->> 'admin')::uuid)
    returning id into cid;
    insert into public.parties (org_id, case_id, role, name, address, aadhaar_last4)
      values (org, cid, 'borrower', ${q(c.borrower)}, 'Synthetic address, Bhopal', '${2000 + c.i}');
    insert into public.loans (org_id, case_id, account_last4, facility_type, sanction_date, sanction_amount_paise,
      roi_bps, npa_date, outstanding_paise, interest_upto_date)
      values (org, cid, '${5000 + c.i}', 'Term Loan', '2023-08-10', ${c.principal}, 1100, '2025-05-31', ${c.total}, '2026-10-20');${
        c.status === "notice_sent" || c.status === "mediation_12a"
          ? `
    insert into public.notices (org_id, case_id, dispatch_mode, tracking_no, sent_at)
      values (org, cid, 'rpad', 'DEMO-RPAD-${c.i}', '2026-09-01T10:00:00+05:30');`
          : ""
      }${
        c.status === "mediation_12a"
          ? `
    insert into public.mediations (org_id, case_id, authority, applied_at, outcome)
      values (org, cid, 'District Legal Services Authority, Bhopal (Demo)', '2026-08-20', 'pending');`
          : ""
      }${
        c.i % 2 === 0
          ? `
    insert into public.tasks (org_id, case_id, assignee_id, role, kind, instructions)
      values (org, cid, (ids ->> 'field')::uuid, 'field', 'collect_docs', 'Collect sanction letter and statement from the branch (demo).');`
          : ""
      }
  end if;
`);
}

console.log(`  raise notice 'Demo office ready: %', org;
end $demo$;`);
